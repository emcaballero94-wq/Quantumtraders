// One-off generator: samples real coastline data (Natural Earth 110m via
// world-atlas) into a lat/lng grid of "land" points for the landing page's
// dot-globe. Run with `node scripts/generate-land-points.mjs` whenever the
// resolution/spacing needs to change. Output ships as static data — no
// topojson/d3-geo dependency at runtime.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import * as topojson from 'topojson-client'
import { geoContains } from 'd3-geo'

const __dirname = dirname(fileURLToPath(import.meta.url))
const topoPath = join(__dirname, '../node_modules/world-atlas/land-110m.json')
const topo = JSON.parse(readFileSync(topoPath, 'utf-8'))
const land = topojson.feature(topo, topo.objects.land)

const LAT_STEP = 3.6
const LNG_STEP = 3.6
const points = []

for (let lat = -85; lat <= 85; lat += LAT_STEP) {
  for (let lng = -180; lng <= 180; lng += LNG_STEP) {
    if (geoContains(land, [lng, lat])) {
      points.push([Math.round(lat * 100) / 100, Math.round(lng * 100) / 100])
    }
  }
}

const outPath = join(__dirname, '../lib/geo/land-points.ts')
const content = `// Generated by scripts/generate-land-points.mjs from Natural Earth 110m land
// data (via world-atlas) — real coastlines sampled on a ${LAT_STEP}°x${LNG_STEP}° grid.
// Do not hand-edit; re-run the script instead.
export const LAND_POINTS: [number, number][] = ${JSON.stringify(points)}
`
writeFileSync(outPath, content)
console.log(`Wrote ${points.length} land points to ${outPath}`)
